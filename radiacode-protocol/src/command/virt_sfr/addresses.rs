use super::VirtSfr;

pub fn try_from_address(value: u32) -> Result<VirtSfr, ()> {
    match value {
        0x0500 => Ok(VirtSfr::DeviceCtrl),
        0x0502 => Ok(VirtSfr::DeviceLang),
        0x0503 => Ok(VirtSfr::DeviceOn),
        0x0504 => Ok(VirtSfr::DeviceTime),
        0x0510 => Ok(VirtSfr::DispCtrl),
        0x0511 => Ok(VirtSfr::DispBrt),
        0x0512 => Ok(VirtSfr::DispContr),
        0x0513 => Ok(VirtSfr::DispOffTime),
        0x0514 => Ok(VirtSfr::DispOn),
        0x0515 => Ok(VirtSfr::DispDir),
        0x0516 => Ok(VirtSfr::DispBacklightOn),
        0x0520 => Ok(VirtSfr::SoundCtrl),
        0x0521 => Ok(VirtSfr::SoundVol),
        0x0522 => Ok(VirtSfr::SoundOn),
        0x0523 => Ok(VirtSfr::SoundButton),
        0x0530 => Ok(VirtSfr::VibroCtrl),
        0x0531 => Ok(VirtSfr::VibroOn),
        0x0540 => Ok(VirtSfr::LedsCtrl),
        0x0541 => Ok(VirtSfr::Led0Brt),
        0x0542 => Ok(VirtSfr::Led1Brt),
        0x0543 => Ok(VirtSfr::Led2Brt),
        0x0544 => Ok(VirtSfr::Led3Brt),
        0x0545 => Ok(VirtSfr::LedsOn),
        0x05E0 => Ok(VirtSfr::AlarmMode),
        0x05E1 => Ok(VirtSfr::PlaySignal),
        0x0600 => Ok(VirtSfr::MsCtrl),
        0x0601 => Ok(VirtSfr::MsMode),
        0x0602 => Ok(VirtSfr::MsSubMode),
        0x0603 => Ok(VirtSfr::MsRun),
        0x0700 => Ok(VirtSfr::BleTxPwr),
        0x8000 => Ok(VirtSfr::DrLev1UrH),
        0x8001 => Ok(VirtSfr::DrLev2UrH),
        0x8002 => Ok(VirtSfr::DsLev1HundredUr),
        0x8003 => Ok(VirtSfr::DsLev2HundredUr),
        0x8004 => Ok(VirtSfr::DsUnits),
        0x8005 => Ok(VirtSfr::CpsFilter),
        0x8006 => Ok(VirtSfr::RawFilter),
        0x8007 => Ok(VirtSfr::DoseReset),
        0x8008 => Ok(VirtSfr::CrLev1Cp10s),
        0x8009 => Ok(VirtSfr::CrLev2Cp10s),
        0x800C => Ok(VirtSfr::UseNanoSvH),
        0x8010 => Ok(VirtSfr::ChnToKeVA0),
        0x8011 => Ok(VirtSfr::ChnToKeVA1),
        0x8012 => Ok(VirtSfr::ChnToKeVA2),
        0x8013 => Ok(VirtSfr::CrUnits),
        0x8014 => Ok(VirtSfr::DsLev1Ur),
        0x8015 => Ok(VirtSfr::DsLev2Ur),
        0x8020 => Ok(VirtSfr::Cps),
        0x8021 => Ok(VirtSfr::DrUrH),
        0x8022 => Ok(VirtSfr::DsUr),
        0x8024 => Ok(VirtSfr::TempDegC),
        0x8025 => Ok(VirtSfr::AccX),
        0x8026 => Ok(VirtSfr::AccY),
        0x8027 => Ok(VirtSfr::AccZ),
        0x8028 => Ok(VirtSfr::Opt),
        0x8033 => Ok(VirtSfr::RawTempDegC),
        0x8034 => Ok(VirtSfr::TempUpDegC),
        0x8035 => Ok(VirtSfr::TempDnDegC),
        0xC000 => Ok(VirtSfr::VBiasMv),
        0xC001 => Ok(VirtSfr::CompLev),
        0xC002 => Ok(VirtSfr::CalibMode),
        0xC004 => Ok(VirtSfr::DpotRdac),
        0xC005 => Ok(VirtSfr::DpotRdacEeprom),
        0xC006 => Ok(VirtSfr::DpotToler),
        0xFFFF0000 => Ok(VirtSfr::SysMcuId0),
        0xFFFF0001 => Ok(VirtSfr::SysMcuId1),
        0xFFFF0002 => Ok(VirtSfr::SysMcuId2),
        0xFFFF0005 => Ok(VirtSfr::SysDeviceId),
        0xFFFF0006 => Ok(VirtSfr::SysSignature),
        0xFFFF0007 => Ok(VirtSfr::SysRxSize),
        0xFFFF0008 => Ok(VirtSfr::SysTxSize),
        0xFFFF0009 => Ok(VirtSfr::SysBootVersion),
        0xFFFF000A => Ok(VirtSfr::SysTargetVersion),
        0xFFFF000B => Ok(VirtSfr::SysStatus),
        0xFFFF000C => Ok(VirtSfr::SysMcuVref),
        0xFFFF000D => Ok(VirtSfr::SysMcuTemp),
        _ => Err(()),
    }
}
